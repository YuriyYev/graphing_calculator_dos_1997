								 //для графических режимов и реверсивное
								 //знакоместо для текстовых. Эмуляция све-
								 //тового пера включена. Горизонтальная
								 //скорость 8 миков на 8 точек, вертикаль-
								 //ная - 16 миков на 8 точек. Скорость
								 //двойного нажатия установлена на 64
								 //мика в секунду. Горизонтальный и верти-
								 //кальный пределы установлены на размер
								 //экрана в текущем вмдео-режиме.
void SHOWMOUSE(void); //Включает указатель и отменяет все установленные
