void HIDEMOUSE(void); //Выключает указатель, но продолжает отслеживать
/*
ПРИМЕЧАНИЕ: Драйвером ведется счетчик, который декрементируется функцией
			HIDEMOUSE() и инкрементируется(если не равен 0) функцией
			SHOWMOUSE(). Если счетчик равен 0, то указатель отображается.
			Функция RESETMOUSE() устанавливает его в -1.
*/


int GETMOUSEXY(int &xc,int &yc); //Возвращает координаты указателя по ссылкам
